  function normalize(value){
    const code=String(value||'').trim().replace(/_/g,'-').toLowerCase();
    if(code==='pt'||code.startsWith('pt-'))return 'pt-BR';
    const base=code.split('-')[0];
    return Object.prototype.hasOwnProperty.call(COPY,base)?base:'';
  }
  function language(){
    let saved='';try{saved=normalize(localStorage.getItem('match_lang'));}catch(_){}
    return saved||normalize(window.MATCH_LANG)||normalize(document.documentElement.lang)||'en';
  }
  function text(key,values={}){
    const lang=language(),template=COPY[lang][key];
    if(typeof template!=='string')return '';
    return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g,(token,name)=>{
      if(!Object.prototype.hasOwnProperty.call(values,name))return token;
      const value=String(values[name]);
      return lang==='ar'&&name==='title'?'\u2068'+value+'\u2069':value;
    });
  }
  function reason(value){
    if(value==='Shown by MatchApp')return text('shownReason');
    if(value==='Ask AI')return text('askAI');
    return value;
  }
  function paint(node){
    const render=bindings.get(node);if(!render)return;
    const lang=language();node.lang=lang;node.dir=lang==='ar'?'rtl':'ltr';
    render();
  }
  function bind(node,render){
    if(!node||typeof render!=='function')return node;
    bindings.set(node,render);node.setAttribute(marker,'');paint(node);return node;
  }
