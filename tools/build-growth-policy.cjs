'use strict';
// Generate a side-effect-free server copy of the existing browser policy.
// This is not a replacement or a relaxed version of the matching engine.
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const root=path.join(__dirname,'..');
const source=fs.readFileSync(path.join(root,'matching-policy.js'),'utf8').replace(/\r\n/g,'\n');
function between(start,end){const a=source.indexOf(start),b=source.indexOf(end,a);if(a<0||b<0||b<=a)throw new Error('Matching policy extraction failed closed: '+start);return source.slice(a,b).trim();}
const fragments=[
  between('const values =','const GUEST_ID ='),
  between('function hits(','function asEntry('),
  between('function genreFits(','function fitsQuestion('),
  between('function matchesCriteria(','function matches(')
];
const sha=crypto.createHash('sha256').update(source).digest('hex');
const content=`// Generated by tools/build-growth-policy.cjs; do not hand-edit.\n// Pure functions copied from the unchanged matching-policy.js.\n// @ts-nocheck\n${fragments.join('\n\n')}\n\nexport { matchesCriteria };\nexport const policySourceSha = '${sha}';\n`;
const target=path.join(root,'supabase/functions/growth-together/matching-policy.mjs');
if(process.argv.includes('--check')){
 if(!fs.existsSync(target)||fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==content)throw new Error('Generated growth policy is stale; regenerate and run parity tests.');
 console.log('Growth policy matches the exact browser source.');
}else{fs.writeFileSync(target,content);console.log('Wrote pure policy, source SHA '+sha);}
